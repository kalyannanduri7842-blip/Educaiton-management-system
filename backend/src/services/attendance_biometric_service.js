    if (!payload || typeof payload !== 'object') {
      return { valid: false, missing: requiredFields, error: 'Payload must be a non-null object' };
    }
    const missing = requiredFields.filter(f => payload[f] === undefined || payload[f] === null || payload[f] === '');
